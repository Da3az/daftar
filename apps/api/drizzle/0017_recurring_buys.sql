-- Recurring buys (dollar-cost averaging): a plan spends a fixed amount of cash
-- on the market at a fixed cadence.
--
-- Hand-written, like 0006–0016.
--
-- The schedule itself lives in Valkey, as one BullMQ Job Scheduler per plan.
-- **This table is the source of truth for what should be scheduled**; the
-- worker re-declares every active plan's scheduler on boot and removes any
-- scheduler with no active plan behind it, so a Valkey that lost its data
-- comes back with the right schedules.
CREATE TABLE recurring_plans (
  -- `rp-<uuid>`: never all digits and no ':', so it is usable as part of a
  -- BullMQ id and of an order's client id as it is.
  id              text PRIMARY KEY,
  participant_id  bigint NOT NULL REFERENCES participants(id),
  symbol          text NOT NULL REFERENCES markets(symbol),
  -- Cash to spend per run, minor units.
  amount          bigint NOT NULL,
  every_ms        bigint NOT NULL,
  status          text NOT NULL DEFAULT 'active',
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT recurring_plans_id_shape CHECK (id ~ '^rp-[0-9a-f-]{36}$'),
  CONSTRAINT recurring_plans_amount_positive CHECK (amount > 0 AND amount <= 100000000),
  -- At least a minute: a demo cadence, not a high-frequency strategy.
  CONSTRAINT recurring_plans_every_bounded CHECK (every_ms BETWEEN 60000 AND 2678400000),
  CONSTRAINT recurring_plans_status_known CHECK (status IN ('active', 'paused', 'deleted'))
);
