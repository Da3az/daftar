-- One row per scheduled firing that did something — including deciding to do
-- nothing. `UNIQUE (plan_id, scheduled_for)` is the guarantee that a firing
-- delivered twice (a retried job, a duplicated scheduler tick) is one run, and
-- one order: the order's client id is derived from the same two values.
CREATE TABLE recurring_runs (
  id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  plan_id         text NOT NULL REFERENCES recurring_plans(id),
  scheduled_for   timestamptz NOT NULL,
  -- filled | partial | skipped
  status          text NOT NULL,
  order_external_id text,
  quantity        bigint,
  notional        bigint,
  reason          text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT recurring_runs_once UNIQUE (plan_id, scheduled_for),
  CONSTRAINT recurring_runs_status_known CHECK (status IN ('filled', 'partial', 'skipped')),
  CONSTRAINT recurring_runs_skipped_has_reason CHECK (status <> 'skipped' OR reason IS NOT NULL)
);
