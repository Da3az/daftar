-- Idempotency, on both surfaces.
--
-- Two different problems that are often conflated:
--
--  * **`Idempotency-Key` on POST /orders.** The duplicate source is a *client or
--    proxy retry* — a timeout where the request actually succeeded, a mobile
--    network retransmitting, a load balancer retrying a 502. The client chooses
--    the key.
--  * **`POST /webhooks/:provider`.** The duplicate source is the *provider's*
--    at-least-once delivery. The provider chooses the key, and the payload
--    arrives with a signature over raw bytes that must be verified before
--    anything else happens.
--
-- They need different tables because they need different columns: a client key
-- has to remember the response it produced so a retry gets the same one; a
-- webhook key has to remember a payload hash so "same id, different body" is
-- detectable at all.

--------------------------------------------------------------------------------
-- 1. Client idempotency keys.
--------------------------------------------------------------------------------
--
-- **Enforced by the UNIQUE index, not by a lookup.** The naive shape —
--
--     SELECT ... WHERE key = $1;  if (none) { do the work; INSERT }
--
-- has the same read-then-write race as Phase 1's ledger, with the same outcome:
-- two concurrent retries both see no row, both do the work, and the customer is
-- charged twice. The correct shape is to let the database arbitrate:
--
--     INSERT ... ON CONFLICT (key) DO NOTHING RETURNING id
--
-- Exactly one caller gets a row back. That caller owns the request; everyone
-- else reads what it produced. Both paths exist in the code behind
-- `DAFTAR_NAIVE_IDEMPOTENCY`, so the race is runnable rather than described.

CREATE TYPE idempotency_state AS ENUM (
  -- Claimed by a request that is still working. A concurrent retry arriving here
  -- must NOT be told "success" — the work may still fail.
  'in_progress',
  -- Finished. `response_status` and `response_body` are the authoritative reply
  -- to any further retry with this key.
  'completed',
  -- Finished by failing. Kept rather than deleted so a retry storm against a
  -- permanently-failing request does not re-run the work every time.
  'failed'
);
--> statement-breakpoint

CREATE TABLE idempotency_keys (
  id          bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- The client's key, scoped by route. Scoped because the same key on a
  -- different endpoint is a different request, and a client reusing a UUID
  -- across two endpoints should not have the second silently return the first's
  -- response.
  route       text NOT NULL,
  key         text NOT NULL,

  -- SHA-256 of the canonical request body.
  --
  -- This is what makes key reuse *detectable*. A client that sends the same key
  -- with a different body has a bug, and the honest answer is 422 rather than
  -- replaying an unrelated response. Without the hash there is no way to tell
  -- that case from a legitimate retry.
  request_hash text NOT NULL,

  state       idempotency_state NOT NULL DEFAULT 'in_progress',

  -- The response to replay. NULL while in_progress.
  response_status integer,
  response_body   jsonb,

  -- The order this key produced, when it produced one.
  order_id    bigint REFERENCES orders(id),

  created_at  timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,

  -- A completed row must carry the response it is promising to replay.
  CONSTRAINT idempotency_completed_has_response
    CHECK ((state = 'completed') = (response_status IS NOT NULL)),

  CONSTRAINT idempotency_terminal_has_timestamp
    CHECK ((state = 'in_progress') = (completed_at IS NULL))
);
--> statement-breakpoint

-- **The constraint that does the actual work.** Everything else is bookkeeping.
CREATE UNIQUE INDEX idempotency_keys_route_key ON idempotency_keys (route, key);
--> statement-breakpoint

-- For the reaper. Keys are not kept forever: the table would grow without
-- bound, and a key's useful life is the window in which a client might retry.
CREATE INDEX idempotency_keys_created_at_idx ON idempotency_keys (created_at);
--> statement-breakpoint

--------------------------------------------------------------------------------
-- 2. Inbound webhook events.
--------------------------------------------------------------------------------

CREATE TYPE webhook_state AS ENUM (
  -- Stored, signature verified, not yet acted on.
  'received',
  -- Being acted on right now.
  --
  -- **This value is why the table has a state column at all.** The common
  -- shortcut is "insert the event id, and if the insert conflicts return 200
  -- because we have seen it". That returns success for work that may still be
  -- running or may have failed — in the one phase whose entire subject is
  -- exactly-once. A replay arriving here gets 409, not 200.
  'processing',
  -- Acted on. A replay gets 200 and nothing re-runs.
  'processed',
  -- Acted on and failed permanently. A replay gets the failure, not a retry.
  'failed',
  -- Signature verified and deliberately ignored — an event type this system
  -- does not care about. Recorded so the Settlements page can show that it
  -- arrived and was a no-op, rather than showing nothing.
  'ignored'
);
--> statement-breakpoint

CREATE TABLE webhook_events (
  id            bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  provider      text NOT NULL,

  -- The provider's own event id. The primary de-duplication key.
  idempotency_key text NOT NULL,

  -- The object this event is about, and what happened to it.
  --
  -- Present because **an event id alone is insufficient.** The same underlying
  -- change can arrive as two separately generated events with different ids —
  -- a provider replaying from a different worker, a backfill, an operator
  -- re-sending from a dashboard. De-duplicating on the event id alone would
  -- process that change twice. Keying on (object_id, event_type) as well is
  -- what catches it.
  object_id     text NOT NULL,
  event_type    text NOT NULL,

  -- SHA-256 of the **raw request bytes**, before any parsing.
  --
  -- Two jobs. First, it makes "same key, different payload" detectable — which
  -- is a provider bug or an attack, and either way needs to be logged and
  -- alerted rather than silently accepted. Second, it is computed over the raw
  -- bytes, which is the same thing the signature covers, so it is a faithful
  -- fingerprint of what was actually signed rather than of a re-serialisation.
  payload_hash  text NOT NULL,

  -- The raw body, kept for the Settlements page and for replay. jsonb for
  -- queryability; the hash above is the authority on what the bytes were.
  payload       jsonb NOT NULL,

  signature_valid boolean NOT NULL,

  -- The provider's signed timestamp, and whether it was inside the tolerance
  -- window. Recorded separately from `signature_valid` because a correctly
  -- signed but stale payload is a *replay*, not a forgery, and the difference
  -- matters when reading the table later.
  signed_at     timestamptz,
  within_window boolean NOT NULL,

  state         webhook_state NOT NULL DEFAULT 'received',

  -- The ledger transaction this event produced, if any.
  transaction_id bigint REFERENCES ledger_transactions(id),

  -- How many times this key has been delivered, including the first. Makes the
  -- duplicate rate observable without a separate metrics pipeline.
  delivery_count integer NOT NULL DEFAULT 1,

  error_detail  text,

  received_at   timestamptz NOT NULL DEFAULT now(),
  processed_at  timestamptz,

  CONSTRAINT webhook_delivery_count_positive CHECK (delivery_count >= 1),

  CONSTRAINT webhook_terminal_has_timestamp
    CHECK ((state IN ('processed', 'failed', 'ignored')) = (processed_at IS NOT NULL))
);
--> statement-breakpoint

-- The primary de-duplication constraint.
CREATE UNIQUE INDEX webhook_events_provider_key ON webhook_events (provider, idempotency_key);
--> statement-breakpoint

-- The secondary one: the same change arriving under a different event id.
-- Deliberately NOT unique — a legitimate sequence of events can touch one
-- object repeatedly (received, then settled, then reconciled). It is an index so
-- the check is cheap, and the application decides whether a given
-- (object, type) pair is a duplicate.
CREATE INDEX webhook_events_object_idx ON webhook_events (provider, object_id, event_type);
--> statement-breakpoint

CREATE INDEX webhook_events_received_at_idx ON webhook_events (received_at);
--> statement-breakpoint

-- Same-key-different-payload, as a view. Empty is the healthy state.
--
-- A row here means a provider sent two different bodies under one event id, or
-- someone replayed a modified payload past the signature check. Either is worth
-- a page, and the payload hash is the only reason it is visible.
CREATE OR REPLACE VIEW webhook_payload_conflicts AS
SELECT provider, idempotency_key, count(DISTINCT payload_hash) AS distinct_payloads
  FROM webhook_events
 GROUP BY provider, idempotency_key
HAVING count(DISTINCT payload_hash) > 1;
--> statement-breakpoint

--------------------------------------------------------------------------------
-- 3. The order's idempotency key, for display.
--------------------------------------------------------------------------------
--
-- Denormalised onto `orders` so the Transactions page can show which key
-- produced an order without a join, and so a support question ("did this retry
-- create a second order?") is answerable in one query.
ALTER TABLE orders ADD COLUMN idempotency_key text;
--> statement-breakpoint

CREATE INDEX orders_idempotency_key_idx ON orders (idempotency_key)
  WHERE idempotency_key IS NOT NULL;
