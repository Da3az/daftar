-- The withdrawal saga: a withdrawal is no longer one ledger transaction but a
-- sequence of states, with the money parked in a hold account between the
-- request and the rail's answer.
--
-- Hand-written, like 0006–0014.
--
-- ## A note on `ALTER TYPE … ADD VALUE`
--
-- drizzle's migrator applies every pending migration in **one** transaction,
-- and PostgreSQL refuses to *use* an enum value in the transaction that added
-- it ("unsafe use of new value"). Adding is fine. So nothing in this file — no
-- CHECK, no default, no index predicate — mentions `customer_hold`, `hold` or
-- `release`; only the application does, after this has committed.

ALTER TYPE account_kind ADD VALUE IF NOT EXISTS 'customer_hold';
--> statement-breakpoint
ALTER TYPE transaction_kind ADD VALUE IF NOT EXISTS 'hold';
--> statement-breakpoint
ALTER TYPE transaction_kind ADD VALUE IF NOT EXISTS 'release';
--> statement-breakpoint

--------------------------------------------------------------------------------
-- The states
--------------------------------------------------------------------------------
--
--   requested ──► held ──► submitted ──► confirmed            (settled: hold → external:funding)
--         │        ▲  │        │  │
--         └► review┘  │        │  └► held        (rail never saw it: resubmit)
--              │      │        ├──► review       (rail undecided past the deadline)
--              ▼      │        ▼
--            failed ◄─┘──── failed ──► released  (hold → guest cash)
--
-- `requested` exists only in the history: the request transaction moves the
-- cash into the hold account and writes the row as `held` (or `review`, over
-- the threshold) in the same commit, so there is no window in which a
-- withdrawal is requested and its money still spendable.
CREATE TYPE withdrawal_state AS ENUM (
  'requested', 'held', 'review', 'submitted', 'confirmed', 'failed', 'released'
);
--> statement-breakpoint

CREATE TABLE withdrawals (
  id               bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- `<participant external id>:<client id>`, as for cash movements: a
  -- double-submitted form is one withdrawal.
  external_id      text NOT NULL,
  participant_id   bigint NOT NULL REFERENCES participants(id),
  amount           bigint NOT NULL,
  state            withdrawal_state NOT NULL,

  hold_account_id  bigint NOT NULL REFERENCES accounts(id),

  -- The three ledger transactions a withdrawal can have. Exactly one of
  -- settle / release ever exists, and each at most once — these columns are
  -- where "the job ran twice, so the guest was paid twice" is made impossible
  -- by the database rather than by the job's own care.
  hold_tx_id       bigint NOT NULL REFERENCES ledger_transactions(id),
  settle_tx_id     bigint REFERENCES ledger_transactions(id),
  release_tx_id    bigint REFERENCES ledger_transactions(id),

  -- The reference the rail is given, and keys its idempotency on. Stable
  -- across resubmissions: a resubmit of a payment the rail did receive must
  -- be recognised as the same payment.
  rail_reference   text NOT NULL,
  submit_attempts  integer NOT NULL DEFAULT 0,
  last_rail_status text,
  review_reason    text,

  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  submitted_at     timestamptz,
  decided_at       timestamptz,

  CONSTRAINT withdrawals_external_id_key UNIQUE (external_id),
  CONSTRAINT withdrawals_rail_reference_key UNIQUE (rail_reference),
  CONSTRAINT withdrawals_hold_tx_key UNIQUE (hold_tx_id),
  CONSTRAINT withdrawals_settle_tx_key UNIQUE (settle_tx_id),
  CONSTRAINT withdrawals_release_tx_key UNIQUE (release_tx_id),
  CONSTRAINT withdrawals_amount_positive CHECK (amount > 0),
  CONSTRAINT withdrawals_settled_xor_released CHECK (settle_tx_id IS NULL OR release_tx_id IS NULL),
  CONSTRAINT withdrawals_confirmed_iff_settled CHECK ((state = 'confirmed') = (settle_tx_id IS NOT NULL)),
  CONSTRAINT withdrawals_released_iff_release_tx CHECK ((state = 'released') = (release_tx_id IS NOT NULL)),
  CONSTRAINT withdrawals_submit_attempts_bounded CHECK (submit_attempts BETWEEN 0 AND 20)
);
--> statement-breakpoint

CREATE INDEX withdrawals_participant_idx ON withdrawals (participant_id, id DESC);
--> statement-breakpoint
-- The sweeper's and the admin screen's scan: everything not yet terminal.
CREATE INDEX withdrawals_open_idx ON withdrawals (state, updated_at)
  WHERE state NOT IN ('confirmed', 'released');
--> statement-breakpoint

--------------------------------------------------------------------------------
-- History, written by the database
--------------------------------------------------------------------------------
--
-- Append-only, and filled by the trigger below rather than by the application,
-- so a code path that changes the state without recording it cannot exist.
-- The reason and actor come from transaction-local settings the application
-- sets just before the change (`daftar.transition_reason`, `daftar.actor`).
CREATE TABLE withdrawal_transitions (
  id             bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  withdrawal_id  bigint NOT NULL REFERENCES withdrawals(id),
  from_state     withdrawal_state,
  to_state       withdrawal_state NOT NULL,
  reason         text,
  actor          text,
  at             timestamptz NOT NULL DEFAULT clock_timestamp()
);
--> statement-breakpoint
CREATE INDEX withdrawal_transitions_withdrawal_idx ON withdrawal_transitions (withdrawal_id, id);
--> statement-breakpoint
REVOKE UPDATE, DELETE, TRUNCATE ON withdrawal_transitions FROM PUBLIC;
--> statement-breakpoint

CREATE FUNCTION withdrawal_legal_transition(f withdrawal_state, t withdrawal_state)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
  SELECT (f, t) IN (
    ('requested', 'held'), ('requested', 'review'),
    ('review', 'held'), ('review', 'failed'),
    ('held', 'submitted'), ('held', 'review'), ('held', 'failed'),
    ('submitted', 'confirmed'), ('submitted', 'failed'),
    ('submitted', 'held'), ('submitted', 'review'),
    ('failed', 'released')
  )
$$;
--> statement-breakpoint

CREATE FUNCTION withdrawals_record_transition() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  reason text := nullif(current_setting('daftar.transition_reason', true), '');
  actor  text := nullif(current_setting('daftar.actor', true), '');
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.state NOT IN ('held', 'review') THEN
      RAISE EXCEPTION 'a withdrawal starts held or in review, not %', NEW.state
        USING ERRCODE = 'check_violation';
    END IF;
    INSERT INTO withdrawal_transitions (withdrawal_id, from_state, to_state, reason, actor)
    VALUES (NEW.id, NULL, 'requested', 'requested by the guest', actor),
           (NEW.id, 'requested', NEW.state, reason, actor);
    RETURN NEW;
  END IF;

  IF NEW.state IS DISTINCT FROM OLD.state THEN
    IF NOT withdrawal_legal_transition(OLD.state, NEW.state) THEN
      RAISE EXCEPTION 'illegal withdrawal transition % -> %', OLD.state, NEW.state
        USING ERRCODE = 'check_violation';
    END IF;
    INSERT INTO withdrawal_transitions (withdrawal_id, from_state, to_state, reason, actor)
    VALUES (NEW.id, OLD.state, NEW.state, reason, actor);
    NEW.updated_at := now();
  END IF;

  -- Identity of a withdrawal never changes after the request.
  IF NEW.amount <> OLD.amount OR NEW.participant_id <> OLD.participant_id
     OR NEW.hold_account_id <> OLD.hold_account_id OR NEW.hold_tx_id <> OLD.hold_tx_id
     OR NEW.rail_reference <> OLD.rail_reference THEN
    RAISE EXCEPTION 'a withdrawal''s amount, owner, hold and reference are fixed'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$$;
--> statement-breakpoint

CREATE TRIGGER withdrawals_insert_transition
  AFTER INSERT ON withdrawals
  FOR EACH ROW EXECUTE FUNCTION withdrawals_record_transition();
--> statement-breakpoint
CREATE TRIGGER withdrawals_update_transition
  BEFORE UPDATE ON withdrawals
  FOR EACH ROW EXECUTE FUNCTION withdrawals_record_transition();
--> statement-breakpoint

--------------------------------------------------------------------------------
-- The simulated payout rail
--------------------------------------------------------------------------------
--
-- Stands in for a bank. Conceptually *outside* this system — it lives in the
-- same database only because a demo has nowhere else to put it, and nothing in
-- the saga reads these tables except through `exchange/rail.ts`, the way it
-- would call a real provider's API.
--
-- Idempotent by reference: submitting a reference it already holds returns the
-- existing payment rather than creating a second one. A rail that is not
-- idempotent cannot be retried safely, and then the saga's only honest answer
-- to a timeout is a human.
CREATE TABLE sim_rail_payments (
  reference     text PRIMARY KEY,
  amount        bigint NOT NULL,
  -- pending → confirmed | rejected
  status        text NOT NULL,
  confirm_at    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  decided_at    timestamptz,
  CONSTRAINT sim_rail_status_known CHECK (status IN ('pending', 'confirmed', 'rejected'))
);
--> statement-breakpoint

-- Chaos knobs, one row. Percentages are per submission.
CREATE TABLE sim_rail_config (
  id                         boolean PRIMARY KEY DEFAULT true CHECK (id),
  -- Recorded, then the caller sees a timeout: the outcome is unknown to it.
  timeout_but_succeeded_pct  integer NOT NULL DEFAULT 0,
  -- Never recorded; the caller sees a timeout.
  drop_pct                   integer NOT NULL DEFAULT 0,
  -- Recorded as rejected.
  reject_pct                 integer NOT NULL DEFAULT 0,
  latency_ms                 integer NOT NULL DEFAULT 50,
  -- How long an accepted payment stays pending before it confirms.
  confirm_after_ms           integer NOT NULL DEFAULT 5000,
  updated_at                 timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sim_rail_pcts CHECK (
    timeout_but_succeeded_pct BETWEEN 0 AND 100 AND drop_pct BETWEEN 0 AND 100
    AND reject_pct BETWEEN 0 AND 100
    AND timeout_but_succeeded_pct + drop_pct + reject_pct <= 100
  ),
  CONSTRAINT sim_rail_latency CHECK (latency_ms BETWEEN 0 AND 60000 AND confirm_after_ms BETWEEN 0 AND 3600000)
);
--> statement-breakpoint
