-- The transactional outbox.
--
-- ## The problem: a dual write cannot be made atomic
--
-- The naive way to publish an event after a ledger write:
--
--   BEGIN; insert entries; update balances; COMMIT;
--   await broker.publish(event);          -- <- a second, independent write
--
-- There is no atomicity across those two systems. Kill the process between them
-- and the money has moved while nothing downstream ever hears about it. No
-- amount of try/catch fixes it: the failure window is *between* two successful
-- operations, not inside either.
--
-- Reversing the order is worse — publish first and a crash before COMMIT means
-- the event describes a transaction that never happened. Wrapping the publish in
-- the database transaction is worse still: it holds row locks for the duration
-- of a network call to the broker, so one slow consumer pins connection-pool
-- slots and blocks VACUUM from reclaiming the table.
--
-- ## The fix: make the event part of the same transaction
--
-- The outbox row is written in the **same database transaction** as the entries
-- it describes, so the two commit or roll back together — one write, one
-- atomicity domain. A separate worker then claims, commits, and publishes.
--
-- Delivery is therefore **at-least-once**, never exactly-once: the worker can
-- publish successfully and then die before marking the row done, and the next
-- poll will publish it again. That is not a defect to be fixed; it is the
-- honest guarantee of this design, and consumers must be idempotent. Phase 4's
-- webhook endpoint is the worked example of a consumer that is.

CREATE TYPE outbox_state AS ENUM (
  -- Written with the ledger transaction. Nothing has tried to publish it yet.
  'pending',
  -- Claimed by a worker that is publishing it right now.
  'in_flight',
  -- Published and acknowledged.
  'published',
  -- Failed `max_attempts` times. Parked for a human, never retried
  -- automatically.
  'dead'
);
--> statement-breakpoint

CREATE TABLE outbox (
  id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- The ledger transaction this event describes. The foreign key is what makes
  -- "the outbox row and the entries commit together" checkable rather than
  -- merely intended: an outbox row cannot reference a transaction that was
  -- rolled back, because the transaction row would not exist.
  transaction_id  bigint NOT NULL REFERENCES ledger_transactions(id),

  -- Which account this event is *about*, and the basis of the ordering
  -- guarantee below. Not nullable: an event with no account cannot be ordered
  -- relative to anything, and every event this system emits is about one.
  account_id      bigint NOT NULL REFERENCES accounts(id),

  event_type      text NOT NULL,
  payload         jsonb NOT NULL,

  state           outbox_state NOT NULL DEFAULT 'pending',

  -- Attempt counter and backoff schedule. `available_at` is when this row next
  -- becomes eligible; the claim query filters on it, so a failing row backs off
  -- without blocking anything behind it.
  attempts        integer NOT NULL DEFAULT 0,
  max_attempts    integer NOT NULL DEFAULT 8,
  available_at    timestamptz NOT NULL DEFAULT now(),

  last_error      text,

  -- Set when a worker claims the row, so a crashed worker's rows can be
  -- identified and reclaimed rather than sitting in_flight forever.
  claimed_at      timestamptz,
  claimed_by      text,

  created_at      timestamptz NOT NULL DEFAULT now(),
  published_at    timestamptz NOT NULL DEFAULT 'infinity',

  CONSTRAINT outbox_attempts_bounded CHECK (attempts >= 0 AND attempts <= max_attempts),
  CONSTRAINT outbox_max_attempts_positive CHECK (max_attempts > 0),

  -- A published row has a real timestamp; everything else keeps the sentinel.
  -- `'infinity'` rather than NULL so the reaper's index below is a plain btree
  -- range scan with no NULL handling.
  CONSTRAINT outbox_published_has_timestamp
    CHECK ((state = 'published') = (published_at <> 'infinity')),

  CONSTRAINT outbox_in_flight_has_claim
    CHECK ((state = 'in_flight') = (claimed_at IS NOT NULL))
);
--> statement-breakpoint

--------------------------------------------------------------------------------
-- Ordering: the shard column, and why FOR UPDATE SKIP LOCKED is not enough
--------------------------------------------------------------------------------
--
-- `SELECT ... FOR UPDATE SKIP LOCKED` is the standard way to let N workers share
-- a queue, and it does **not** preserve per-account order. Two events for one
-- account get claimed by two different workers, and whichever worker's network
-- call completes first publishes first. Event 2 can land before event 1.
--
-- For a ledger that matters: "balance became 50" then "balance became 100"
-- delivered in the other order leaves a consumer with the wrong answer and no
-- way to detect it.
--
-- The fix is to make one account the property of exactly one worker:
--
--     shard = account_id % shard_count
--
-- A worker claims only its own shards. Two events for one account are therefore
-- always claimed by the same worker, in id order, and published in that order.
-- Across accounts there is no ordering guarantee and none is claimed.
--
-- `shard` is a GENERATED column so it cannot drift from `account_id`, and the
-- shard count is baked into the schema rather than configured — changing it
-- requires a migration *and* draining the outbox first, because mid-flight rows
-- would otherwise move between workers and lose their ordering. That is a
-- deliberate cost: a config value here would look harmless and silently break
-- the only guarantee this table makes.
ALTER TABLE outbox
  ADD COLUMN shard smallint
  GENERATED ALWAYS AS ((account_id % 16)::smallint) STORED;
--> statement-breakpoint

-- The claim query's index. Covers the exact predicate the worker uses:
-- eligible rows, in this worker's shards, oldest first.
--
-- Partial, on `state`, because `published` rows dominate the table within hours
-- and including them would make the index mostly dead weight that still has to
-- be maintained on every insert.
CREATE INDEX outbox_claim_idx
  ON outbox (shard, available_at, id)
  WHERE state IN ('pending', 'in_flight');
--> statement-breakpoint

-- For the reaper and for lag measurement.
CREATE INDEX outbox_published_at_idx ON outbox (published_at)
  WHERE state = 'published';
--> statement-breakpoint

-- Dead-letter review. Small by construction, so a plain index is fine.
CREATE INDEX outbox_dead_idx ON outbox (created_at) WHERE state = 'dead';
--> statement-breakpoint

--------------------------------------------------------------------------------
-- Observability views
--------------------------------------------------------------------------------

-- Outbox lag: the age of the oldest unpublished event.
--
-- This is the number to alert on. A growing lag means the worker is down, or
-- slower than the write rate, or stuck on a poison message — and it is visible
-- long before anything else breaks.
CREATE OR REPLACE VIEW outbox_lag AS
SELECT
  count(*) FILTER (WHERE state = 'pending')   AS pending,
  count(*) FILTER (WHERE state = 'in_flight') AS in_flight,
  count(*) FILTER (WHERE state = 'dead')      AS dead,
  coalesce(
    extract(epoch FROM now() - min(created_at) FILTER (WHERE state IN ('pending', 'in_flight'))),
    0
  )::bigint AS oldest_unpublished_seconds,
  -- A row claimed long ago by a worker that then died. Distinct from ordinary
  -- in_flight, and the thing the reclaim query looks for.
  count(*) FILTER (
    WHERE state = 'in_flight' AND claimed_at < now() - interval '5 minutes'
  ) AS stale_claims
  FROM outbox;
--> statement-breakpoint

-- Per-shard depth, so an uneven distribution or one stuck shard is visible
-- rather than averaged away by the aggregate above.
CREATE OR REPLACE VIEW outbox_shard_depth AS
SELECT shard,
       count(*) FILTER (WHERE state = 'pending')   AS pending,
       count(*) FILTER (WHERE state = 'in_flight') AS in_flight,
       count(*) FILTER (WHERE state = 'dead')      AS dead
  FROM outbox
 GROUP BY shard
 ORDER BY shard;
