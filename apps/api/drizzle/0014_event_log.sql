--------------------------------------------------------------------------------
-- Reconciliation — projection vs ledger, with time-to-detect
--------------------------------------------------------------------------------
--
-- Accounts the reconciler has seen an event for and not yet checked. The
-- consumer upserts; the sweep checks and deletes.
CREATE TABLE reconcile_dirty (
  participant_id  bigint NOT NULL,
  symbol          text NOT NULL,
  event_id        bigint NOT NULL,
  marked_at       timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (participant_id, symbol)
);
