--------------------------------------------------------------------------------
-- Positions — average cost, realised P&L
--------------------------------------------------------------------------------
--
-- One row per guest per market, built only from `trade.buy` / `trade.sell`
-- events. Average-cost method, in exact integers:
--
--   buy:  quantity += q;  cost_basis += notional
--   sell: removed = floor(cost_basis * q / quantity)
--         realised_pnl += notional - removed
--         cost_basis -= removed;  quantity -= q
--
-- The floor leaves any remainder in `cost_basis`, so cost is conserved to the
-- cent: the basis removed by every sell plus what is left always equals what
-- was paid. Average entry price is derived (cost_basis / quantity), never
-- stored, so it cannot drift from the two numbers it comes from.
--
-- `last_event_id` is the newest trade event applied. Events for one account
-- arrive in id order; an older id arriving later is out of order, and is
-- applied *and* flagged to the reconciler rather than silently dropped.
CREATE TABLE proj_positions (
  participant_id  bigint NOT NULL,
  symbol          text NOT NULL,
  quantity        bigint NOT NULL DEFAULT 0,
  cost_basis      bigint NOT NULL DEFAULT 0,
  realised_pnl    bigint NOT NULL DEFAULT 0,
  buys            integer NOT NULL DEFAULT 0,
  sells           integer NOT NULL DEFAULT 0,
  last_event_id   bigint NOT NULL,
  updated_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (participant_id, symbol),
  CONSTRAINT proj_positions_quantity_nonneg CHECK (quantity >= 0),
  -- A flat position has no basis left. If this fires, the projection saw a
  -- sell it had no buy for: an event was lost or reordered.
  CONSTRAINT proj_positions_flat_has_no_basis CHECK (quantity > 0 OR cost_basis = 0)
);
