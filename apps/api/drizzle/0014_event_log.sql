CREATE TABLE reconciliation_findings (
  id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  participant_id  bigint NOT NULL,
  symbol          text,
  -- quantity_mismatch | cost_basis_mismatch | realised_mismatch |
  -- out_of_order | hold_balance_mismatch | projection_lagging
  kind            text NOT NULL,
  expected        bigint,
  actual          bigint,
  event_id        bigint,
  detected_at     timestamptz NOT NULL DEFAULT now(),
  -- When the divergence began, where it is known (an injection); NULL when the
  -- reconciler can only say when it noticed.
  introduced_at   timestamptz,
  detail          text
);
