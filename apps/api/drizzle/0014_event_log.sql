--------------------------------------------------------------------------------
-- Dead letters — poison messages, parked for a human
--------------------------------------------------------------------------------
--
-- Keyed by position in the log, not by event id: an undecodable message has no
-- event id to key on.
CREATE TABLE consumer_dead_letters (
  id           bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  consumer     text NOT NULL,
  topic        text NOT NULL,
  partition    integer NOT NULL,
  "offset"     bigint NOT NULL,
  event_id     bigint,
  error        text NOT NULL,
  raw_value    text NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  resolved_at  timestamptz,
  CONSTRAINT consumer_dead_letters_position_key UNIQUE (consumer, topic, partition, "offset")
);
