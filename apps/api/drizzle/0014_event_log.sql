-- Deliberate corruption, for measuring detection. Written by the admin chaos
-- endpoint alongside the corruption itself, so the finding can be timed
-- against when the divergence was introduced.
CREATE TABLE projection_drift_injections (
  id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  participant_id  bigint NOT NULL,
  symbol          text NOT NULL,
  field           text NOT NULL,
  delta           bigint NOT NULL,
  injected_at     timestamptz NOT NULL DEFAULT now(),
  detected_at     timestamptz
);
