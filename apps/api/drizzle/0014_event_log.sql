-- The event log's PostgreSQL side: consumer idempotency, dead letters, and the
-- read models rebuilt from the log.
--
-- Hand-written, like 0006–0013: nothing here is in `schema.ts`.
--
-- Every table below is a **read model or a delivery record**. None holds money;
-- the ledger does. That is why none of them has a foreign key into the ledger:
-- a projection must be droppable and rebuildable without touching, or being
-- blocked by, anything the money depends on.

--------------------------------------------------------------------------------
-- Consumer receipts — the idempotency guarantee
--------------------------------------------------------------------------------
--
-- A consumer writes its receipt in the same transaction as its effect. If the
-- receipt insert conflicts, the event was already applied and the transaction
-- is rolled back. Kafka's committed offset says where to resume; this table
-- says what has happened, and only this one is trusted.
CREATE TABLE consumer_receipts (
  consumer      text NOT NULL,
  event_id      bigint NOT NULL,
  processed_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (consumer, event_id)
);
