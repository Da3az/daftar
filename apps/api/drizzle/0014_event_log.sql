--------------------------------------------------------------------------------
-- Equity snapshots — the series behind the equity chart
--------------------------------------------------------------------------------
--
-- `bucket` is the scheduled snapshot time, truncated, so a snapshot job that
-- runs twice for the same slot writes one row. Values are as of the run:
-- ledger cash (including cash on hold for a withdrawal) plus position
-- quantity at the market's last price.
CREATE TABLE equity_snapshots (
  participant_id  bigint NOT NULL,
  bucket          timestamptz NOT NULL,
  cash            bigint NOT NULL,
  holdings_value  bigint NOT NULL,
  equity          bigint NOT NULL,
  net_contributed bigint NOT NULL,
  taken_at        timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (participant_id, bucket)
);
