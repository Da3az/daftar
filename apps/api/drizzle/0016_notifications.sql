-- In-app notifications. Written by the notify job, read by the guest.
--
-- Hand-written, like 0006–0015.
--
-- `UNIQUE (event_id, kind)` is the dedup guarantee: the notifier consumer can
-- redeliver, the BullMQ job can run twice, and the guest still gets one
-- notification per event. BullMQ's job id is the cheap first line; this is
-- the one that holds.
CREATE TABLE notifications (
  id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  participant_id  bigint NOT NULL REFERENCES participants(id),
  event_id        bigint NOT NULL,
  kind            text NOT NULL,
  title           text NOT NULL,
  body            text,
  -- When the money moved, carried from the event: the start of the latency
  -- the evidence file measures.
  occurred_at     timestamptz NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  read_at         timestamptz,
  CONSTRAINT notifications_event_kind_key UNIQUE (event_id, kind)
);
