-- Participants
--------------------------------------------------------------------------------

CREATE TYPE participant_kind AS ENUM (
  -- A visitor who clicked "enter as guest". Funded once, cannot go negative.
  'guest',
  -- A market-making bot. Unlimited: its accounts are allowed to go negative,
  -- the same way the house's are, so it can always quote both sides.
  'bot'
);
--> statement-breakpoint

CREATE TABLE participants (
  id               bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- Also the `external_id` of the participant's cash account. Its position
  -- account for a market is `<external_id>:<symbol>`, the convention the legacy
  -- order path already uses.
  external_id      text NOT NULL,

  kind             participant_kind NOT NULL,
  display_name     text NOT NULL,

  cash_account_id  bigint NOT NULL REFERENCES accounts(id),

  created_at       timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT participants_external_id_key UNIQUE (external_id),
  CONSTRAINT participants_cash_account_key UNIQUE (cash_account_id)
);
--> statement-breakpoint

--------------------------------------------------------------------------------
-- Orders on the book
--------------------------------------------------------------------------------

CREATE TYPE book_order_type AS ENUM (
  -- Rests on the book at its limit price until filled or cancelled.
  'limit',
  -- Takes whatever is resting, best price first, and never rests: any
  -- unfilled remainder is cancelled in the same transaction.
  'market'
);
--> statement-breakpoint

CREATE TYPE book_order_status AS ENUM (
  -- On the book, possibly partly filled (`filled_quantity > 0`).
  'open',
  'filled',
  -- Withdrawn with `quantity - filled_quantity` unfilled. `cancel_reason` says
  -- by whom.
  'cancelled'
);
--> statement-breakpoint

CREATE TABLE book_orders (
  id               bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- Client-chosen. UNIQUE, so a double-submitted form is one order and a 409
  -- rather than two orders.
  external_id      text NOT NULL,

  participant_id   bigint NOT NULL REFERENCES participants(id),
  symbol           text NOT NULL REFERENCES markets(symbol),

  side             order_side NOT NULL,
  type             book_order_type NOT NULL,

  -- NULL for a market order, which has no price of its own.
  limit_price      bigint,

  quantity         bigint NOT NULL,
  filled_quantity  bigint NOT NULL DEFAULT 0,

  status           book_order_status NOT NULL,
  cancel_reason    text,

  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT book_orders_external_id_key UNIQUE (external_id),

  CONSTRAINT book_orders_quantity_positive CHECK (quantity > 0),
  CONSTRAINT book_orders_filled_in_range
    CHECK (filled_quantity >= 0 AND filled_quantity <= quantity),

  CONSTRAINT book_orders_limit_price_matches_type
    CHECK ((type = 'market') = (limit_price IS NULL)),
  CONSTRAINT book_orders_limit_price_positive CHECK (limit_price > 0),

  -- "Filled" is not a judgement the application gets to make independently of
  -- the arithmetic.
  CONSTRAINT book_orders_filled_means_filled
    CHECK ((status = 'filled') = (filled_quantity = quantity)),

  -- A market order with no price cannot sit in a price-ordered book.
  CONSTRAINT book_orders_market_never_rests
    CHECK (NOT (type = 'market' AND status = 'open')),

  CONSTRAINT book_orders_cancel_has_reason
    CHECK ((status = 'cancelled') = (cancel_reason IS NOT NULL))
);
--> statement-breakpoint

-- The book itself: resting orders for one side of one market, in price then
-- arrival order. Partial, because filled and cancelled orders dominate the
-- table within minutes and the matcher never reads them.
CREATE INDEX book_orders_book_idx
  ON book_orders (symbol, side, limit_price, id)
  WHERE status = 'open';
--> statement-breakpoint

-- "My orders", newest first, and the reservation sum over a participant's open
-- orders.
CREATE INDEX book_orders_participant_idx ON book_orders (participant_id, id DESC);
--> statement-breakpoint

--------------------------------------------------------------------------------
-- Trades
--------------------------------------------------------------------------------

CREATE TABLE trades (
  id               bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  symbol           text NOT NULL REFERENCES markets(symbol),

  -- The resting order's limit price. The taker gets the maker's price, which is
  -- the whole of price-time priority's "price improvement".
  price            bigint NOT NULL,
  quantity         bigint NOT NULL,

  -- quantity x price / 1e8, half-up. The cash that actually moved.
  notional         bigint NOT NULL,

  taker_order_id   bigint NOT NULL REFERENCES book_orders(id),
  maker_order_id   bigint NOT NULL REFERENCES book_orders(id),

  -- Which way the aggressor went. Denormalised from the taker order because
  -- the tape reads it on every poll.
  taker_side       order_side NOT NULL,

  -- The ledger transaction that moved the money. UNIQUE: one trade, one
  -- transaction, and a trade row cannot exist without the entries behind it —
  -- they are written by the same database transaction.
  transaction_id   bigint NOT NULL REFERENCES ledger_transactions(id),

  created_at       timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT trades_transaction_key UNIQUE (transaction_id),
  CONSTRAINT trades_price_positive CHECK (price > 0),
  CONSTRAINT trades_quantity_positive CHECK (quantity > 0),
  CONSTRAINT trades_notional_positive CHECK (notional > 0),
  CONSTRAINT trades_distinct_orders CHECK (taker_order_id <> maker_order_id)
);
--> statement-breakpoint

-- The tape, and the candle aggregation.
CREATE INDEX trades_symbol_id_idx ON trades (symbol, id DESC);
--> statement-breakpoint
CREATE INDEX trades_symbol_created_at_idx ON trades (symbol, created_at);
--> statement-breakpoint

-- A participant's own fills, from either side.
CREATE INDEX trades_taker_order_idx ON trades (taker_order_id);
--> statement-breakpoint
CREATE INDEX trades_maker_order_idx ON trades (maker_order_id);
--> statement-breakpoint

