-- The one market
--------------------------------------------------------------------------------
--
-- DFT, a coin that exists only here. 25.00 to open; prices in cents; quantities
-- in hundredths of a coin; band 1.00 – 10,000.00.
--
-- No accounts are created by this migration. Bot and guest accounts are created
-- by the application when it first needs them, so applying this to a database
-- that holds a measured dataset adds tables and one reference row and moves no
-- row count that an evidence file pins.
INSERT INTO markets
  (symbol, display_name, tick_size, lot_size, min_price, max_price, opening_price, last_price)
VALUES
  ('DFT', 'Daftar Token', 1, 1000000, 100, 1000000, 2500, 2500)
ON CONFLICT (symbol) DO NOTHING;
