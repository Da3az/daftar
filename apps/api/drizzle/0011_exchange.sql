-- The order book.
--
-- Until here every order had one counterparty — the house — and one price, read
-- from a table. This migration adds the other shape: participants post orders
-- at prices of their own choosing, and an order trades only when someone else
-- is willing to take the other side.
--
-- What does NOT change is the ledger. A fill is one `ledger_transactions` row
-- and four `entries` — buyer cash, seller cash, seller position, buyer
-- position — balanced per unit, posted by the same code path as everything
-- else, under the same triggers. The tables below record *why* money moved;
-- `entries` remains the only record that it did.
--
-- Hand-written, like 0006–0010: nothing here is in `schema.ts`, so
-- `drizzle-kit generate` neither sees these tables nor proposes dropping them.
-- No existing enum is altered, deliberately — `ALTER TYPE ... ADD VALUE` on a
-- type that `schema.ts` declares is exactly the snapshot drift 0005 documents.

--------------------------------------------------------------------------------
-- Markets
--------------------------------------------------------------------------------
--
-- Separate from `instruments`, not a row in it. `instruments` is the fixed list
-- the house quotes at a frozen reference price, and the benchmarks run against
-- that table; a symbol whose price moves on every trade does not belong in it,
-- and the legacy order path must not be able to quote it.
CREATE TABLE markets (
  symbol         text PRIMARY KEY,
  display_name   text NOT NULL,

  -- Price increment, in cash minor units. Every limit price is a multiple.
  tick_size      bigint NOT NULL,

  -- Quantity increment, at QUANTITY_SCALE (1e-8). Every order quantity is a
  -- multiple, and so is every fill, because a fill is always a difference of
  -- two multiples.
  lot_size       bigint NOT NULL,

  -- The band a limit price must sit in.
  min_price      bigint NOT NULL,
  max_price      bigint NOT NULL,

  opening_price  bigint NOT NULL,

  -- The price of the most recent trade; the opening price until there is one.
  -- A display convenience maintained by the matching transaction. Nothing is
  -- ever priced from it: a fill's price is the resting order's limit price.
  last_price     bigint NOT NULL,
  last_trade_at  timestamptz,

  CONSTRAINT markets_tick_positive CHECK (tick_size > 0),
  CONSTRAINT markets_lot_positive CHECK (lot_size > 0),
  CONSTRAINT markets_band_ordered CHECK (min_price > 0 AND min_price <= max_price),
  CONSTRAINT markets_band_on_tick
    CHECK (min_price % tick_size = 0 AND max_price % tick_size = 0),
  CONSTRAINT markets_opening_in_band
    CHECK (opening_price BETWEEN min_price AND max_price AND opening_price % tick_size = 0),

  -- **The smallest possible fill is worth at least one cash minor unit.**
  --
  -- notional = quantity * price / 1e8. One lot at the bottom of the band is the
  -- smallest product there can be, so if that is >= 1e8 no fill can round to
  -- 0.00 — which matters because a zero cash leg violates
  -- `entries_amount_nonzero` at COMMIT, after the matching work is done, and
  -- would take the whole incoming order down with it.
  CONSTRAINT markets_min_fill_is_nonzero CHECK (min_price * lot_size >= 100000000)
);
