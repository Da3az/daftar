-- Cash movements on the exchange, and the activity feed the outbox publishes to.
--
-- Until here a guest's cash moved in exactly one way after the opening credit:
-- a fill, under the market lock. This migration adds the tables behind three
-- movements that do NOT take that lock — deposits, withdrawals and transfers
-- between guests — and the consumer side of the outbox.
--
-- As in 0011, the ledger is unchanged. Each of these is an ordinary balanced
-- ledger transaction; the tables below record why it happened.
--
-- Hand-written, like 0006–0011: nothing here is in `schema.ts`.

--------------------------------------------------------------------------------
-- A public handle for each participant
--------------------------------------------------------------------------------
--
-- `participants.external_id` is the session's subject and must stay unguessable
-- (the legacy read endpoints return any account whose id a caller can name), so
-- it cannot be what one guest types to pay another. The handle is: random,
-- unique, safe to show, and useless for anything except being paid.
--
-- Added nullable, backfilled, then constrained — a volatile DEFAULT on ADD
-- COLUMN would be evaluated per existing row anyway, but doing it in three steps
-- keeps the backfill explicit.
ALTER TABLE participants ADD COLUMN handle text;
