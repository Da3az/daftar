--------------------------------------------------------------------------------
-- Deposits
--------------------------------------------------------------------------------
--
-- A deposit is a request to the payment provider, not money. This row records
-- that the request was made; whether it was credited is NOT stored here. That
-- is read from `webhook_events` by `object_id`, because the event is settled in
-- the same database transaction as the ledger entries and this row is not — a
-- status column here would be a second copy of a fact, written separately, and
-- so able to disagree with the first.
CREATE TABLE deposits (
  id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  participant_id  bigint NOT NULL REFERENCES participants(id),

  -- The provider's object id (`objectId` in the event). UNIQUE, and the join key
  -- to `webhook_events.object_id`.
  external_id     text NOT NULL,

  -- The provider's event id — the webhook idempotency key.
  event_id        text NOT NULL,

  amount          bigint NOT NULL,

  -- How many times the simulated provider was asked to deliver the event.
  deliveries      integer NOT NULL,

  created_at      timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT deposits_external_id_key UNIQUE (external_id),
  CONSTRAINT deposits_event_id_key UNIQUE (event_id),
  CONSTRAINT deposits_amount_positive CHECK (amount > 0),
  CONSTRAINT deposits_deliveries_positive CHECK (deliveries >= 1)
);
--> statement-breakpoint

-- The per-guest hourly limit counts recent rows.
CREATE INDEX deposits_participant_created_idx ON deposits (participant_id, created_at DESC);
--> statement-breakpoint

--------------------------------------------------------------------------------
-- Withdrawals and transfers
--------------------------------------------------------------------------------

CREATE TYPE cash_movement_kind AS ENUM (
  -- Cash leaves the system: guest debited, `external:funding` credited.
  'withdrawal',
  -- Cash moves between two guests.
  'transfer'
);
--> statement-breakpoint

CREATE TABLE cash_movements (
  id                 bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  -- `<participant external id>:<client id>`. UNIQUE, so a double-submitted form
  -- is one movement and a 409 rather than two.
  external_id        text NOT NULL,

  kind               cash_movement_kind NOT NULL,

  -- Who gave the instruction, and whose cash was debited.
  participant_id     bigint NOT NULL REFERENCES participants(id),

  -- The receiving guest. NULL for a withdrawal.
  counterparty_id    bigint REFERENCES participants(id),

  amount             bigint NOT NULL,

  -- The ledger transaction that moved the money. Written in the same database
  -- transaction, so a row here cannot exist without the entries behind it.
  transaction_id     bigint NOT NULL REFERENCES ledger_transactions(id),

  created_at         timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT cash_movements_external_id_key UNIQUE (external_id),
  CONSTRAINT cash_movements_transaction_key UNIQUE (transaction_id),
  CONSTRAINT cash_movements_amount_positive CHECK (amount > 0),
  CONSTRAINT cash_movements_counterparty_matches_kind
    CHECK ((kind = 'transfer') = (counterparty_id IS NOT NULL)),
  CONSTRAINT cash_movements_not_to_self
    CHECK (counterparty_id IS NULL OR counterparty_id <> participant_id)
);
--> statement-breakpoint

CREATE INDEX cash_movements_participant_idx ON cash_movements (participant_id, id DESC);
--> statement-breakpoint

--------------------------------------------------------------------------------
-- The activity feed: what the outbox worker publishes to
--------------------------------------------------------------------------------
--
-- The consumer side of the outbox. Delivery is at-least-once — the worker can
-- publish and die before marking the row published, and the next poll
-- republishes — so the consumer has to be idempotent, and here it is by
-- construction: `UNIQUE (outbox_event_id)` with `ON CONFLICT DO NOTHING`.
-- A redelivered event is one feed row, not two.
--
-- No foreign key to `outbox`: published outbox rows are reaped after a day and
-- the feed outlives them.
CREATE TABLE exchange_activity (
  id               bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

  participant_id   bigint NOT NULL REFERENCES participants(id),
  outbox_event_id  bigint NOT NULL,

  event_type       text NOT NULL,
  payload          jsonb NOT NULL,

  -- When the money moved (the outbox row's `created_at`), not when the feed
  -- heard about it. The gap between the two is the worker's lag.
  occurred_at      timestamptz NOT NULL,
  published_at     timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT exchange_activity_outbox_event_key UNIQUE (outbox_event_id)
);
--> statement-breakpoint

CREATE INDEX exchange_activity_participant_idx ON exchange_activity (participant_id, id DESC);
